package lessons.basics_and_control;

public class MathClass {
    public static void main(String[] args) {
        System.out.println(Math.abs(-125));
        System.out.println(Math.decrementExact(20));
        System.out.println(Math.decrementExact(Integer.MAX_VALUE));
        System.out.println(Math.floorDiv(25, 3));
        System.out.println(Math.log10(100));
        System.out.println(Math.nextAfter(12.5, 13));
        System.out.println(Math.random());

    }
    
}

