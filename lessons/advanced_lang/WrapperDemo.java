package lessons.advanced_lang;

public class WrapperDemo {
    public static void main(String[] args) {

        /*
        
        Java provides wrapper classes for each primitive datatype
        by using wrapper classes instead of primitives, java becomes pure object oriented
        generics, collections and api uses objects not primitives, so wrapper classes are used 
        
        // Integer i = new Integer(10); deapreciated 
        Integer i = Integer.valueOf(10); // better way 
        Integer a = 15; // internally calls valueOf() method

        int a1 = 20;
        Integer c1 = Integer.valueOf(a1); // boxing
        Integer b1 = a1; // auto-boxing -> coverting primitives into object of their wrapper class

        int d1 = Integer.valueOf(a1); // un-boxing
        int k1 = b1; // auto un-boxing -> coverting object of wrapper class back into primitive type

        Character c = 'B';
        Character d = Character.valueOf('Y');

        Float f = 25.6f;

        Integer k = Integer.valueOf("25.4"); // converts string into integer
        Integer j = Integer.valueOf(k);

        */


    }
    
}

